import { z } from "zod";

/** Branch prefixes that AI coding agents use by default. */
export const DEFAULT_AI_BRANCH_PREFIXES = ["cursor/", "codex/", "copilot/", "claude/", "devin/", "ai/"];
/** PR labels that mark a change as AI-generated. Matched case-insensitively. */
export const DEFAULT_AI_LABELS = ["ai-generated", "ai-assisted", "generated-by-ai"];

/** Names and emails of AI coding tools as they appear in Co-authored-by trailers and bot logins. */
const KNOWN_AI = /\b(claude|anthropic|copilot|cursor(?:agent)?|codex|openai|chatgpt|gpt-[0-9]|gemini|devin|aider|codeium|windsurf|codewhisperer|tabnine|jules)\b/i;
/** "Generated with Claude Code", "Generated by Copilot", "🤖 Generated with ..." and similar. */
const DEFAULT_MARKERS = [
  /generated (?:with|by|using) \[?(?:claude|copilot|cursor|codex|chatgpt|gemini|devin|aider|an? (?:ai|llm))/i,
  /🤖 generated with/i,
];

export const aiDetectionSchema = z
  .object({
    /** Off by default: nothing is detected and no policy applies. */
    enabled: z.boolean().default(false),
    /** Look for Co-authored-by trailers of known AI tools and generator markers in commit messages. */
    commit_trailers: z.boolean().default(true),
    /** Head branch prefixes that mark a PR as AI-generated. */
    branch_prefixes: z.array(z.string().min(1)).default(DEFAULT_AI_BRANCH_PREFIXES),
    /** PR labels that mark a PR as AI-generated (case-insensitive). */
    labels: z.array(z.string().min(1)).default(DEFAULT_AI_LABELS),
    /** Extra case-insensitive phrases to look for in the PR body/title and commit messages. */
    markers: z.array(z.string().min(1)).default([]),
    policy: z
      .object({
        /** These checks become required (and must actually run) when the change is AI-generated. */
        require_checks: z.array(z.string().min(1)).default([]),
        /** AI-generated changes fail the gate until someone approves them (docs/approvals.md). */
        require_approval: z.boolean().default(false),
      })
      .strict()
      .default({}),
  })
  .strict()
  .default({});

export type AiDetectionConfig = z.infer<typeof aiDetectionSchema>;

/** What we know about a change, from the code host (PR) and from git (commits). */
export interface ChangeSignals {
  commitMessages?: string[];
  branch?: string;
  labels?: string[];
  title?: string;
  body?: string;
  author?: string;
}

export interface AiDetection {
  generated: boolean;
  /** Human-readable reasons, e.g. `branch "cursor/fix-x" starts with "cursor/"`. */
  signals: string[];
}

const clip = (s: string, n = 120) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

/** Provider-agnostic heuristics. Pure: no I/O. */
export function detectAiGenerated(cfg: AiDetectionConfig, s: ChangeSignals): AiDetection {
  if (!cfg.enabled) return { generated: false, signals: [] };
  const signals: string[] = [];
  const extra = cfg.markers.map((m) => m.toLowerCase());
  const markerIn = (text: string): string | undefined => {
    for (const re of DEFAULT_MARKERS) {
      const m = re.exec(text);
      if (m) return m[0];
    }
    const lower = text.toLowerCase();
    return extra.find((m) => lower.includes(m));
  };

  if (s.branch) {
    const prefix = cfg.branch_prefixes.find((p) => s.branch!.toLowerCase().startsWith(p.toLowerCase()));
    if (prefix) signals.push(`branch "${clip(s.branch)}" starts with "${prefix}"`);
  }
  const wanted = new Set(cfg.labels.map((l) => l.toLowerCase()));
  for (const label of s.labels ?? []) if (wanted.has(label.toLowerCase())) signals.push(`PR label "${clip(label)}"`);
  if (s.author && /\[bot\]$/i.test(s.author) && KNOWN_AI.test(s.author)) signals.push(`PR author ${s.author}`);
  for (const [where, text] of [["PR title", s.title], ["PR body", s.body]] as const) {
    const m = text ? markerIn(text) : undefined;
    if (m) signals.push(`${where} mentions "${clip(m)}"`);
  }
  if (cfg.commit_trailers) {
    const seen = new Set<string>();
    for (const msg of s.commitMessages ?? []) {
      for (const m of msg.matchAll(/^co-authored-by:\s*(.+)$/gim)) {
        const who = m[1]!.trim();
        if (KNOWN_AI.test(who) && !seen.has(who.toLowerCase())) {
          seen.add(who.toLowerCase());
          signals.push(`commit trailer "Co-authored-by: ${clip(who)}"`);
        }
      }
      const marker = markerIn(msg);
      if (marker && !seen.has(`marker:${marker.toLowerCase()}`)) {
        seen.add(`marker:${marker.toLowerCase()}`);
        signals.push(`commit message mentions "${clip(marker)}"`);
      }
    }
  }
  return { generated: signals.length > 0, signals };
}
