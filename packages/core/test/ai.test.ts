import { describe, expect, it } from "vitest";
import { GateConfigError, aiDetectionSchema, detectAiGenerated, evaluateGate, parseGateConfig } from "../src/index.ts";

const on = aiDetectionSchema.parse({ enabled: true });

describe("detectAiGenerated", () => {
  it("is off unless enabled", () => {
    expect(detectAiGenerated(aiDetectionSchema.parse({}), { branch: "cursor/x" })).toEqual({ generated: false, signals: [] });
  });

  it("finds Co-authored-by trailers of known AI tools, once each", () => {
    const d = detectAiGenerated(on, {
      commitMessages: [
        "fix: x\n\nCo-authored-by: Claude <noreply@anthropic.com>",
        "fix: y\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nCo-authored-by: Jane Doe <jane@example.com>",
        "feat: z\n\nCo-authored-by: Cursor Agent <cursoragent@cursor.com>",
      ],
    });
    expect(d.generated).toBe(true);
    expect(d.signals).toEqual([
      'commit trailer "Co-authored-by: Claude <noreply@anthropic.com>"',
      'commit trailer "Co-authored-by: Cursor Agent <cursoragent@cursor.com>"',
    ]);
  });

  it("ignores human co-authors and plain commits", () => {
    expect(detectAiGenerated(on, { commitMessages: ["Co-authored-by: Jane Doe <jane@example.com>", "refactor"] }).generated).toBe(false);
  });

  it("finds generator markers, branch prefixes, labels and AI bot authors", () => {
    const d = detectAiGenerated(on, {
      commitMessages: ["add thing\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"],
      branch: "codex/add-thing",
      labels: ["bug", "AI-Generated"],
      body: "Summary\n\nGenerated by Copilot",
      author: "copilot-swe-agent[bot]",
    });
    expect(d.signals).toEqual([
      'branch "codex/add-thing" starts with "codex/"',
      'PR label "AI-Generated"',
      "PR author copilot-swe-agent[bot]",
      'PR body mentions "Generated by Copilot"',
      'commit message mentions "Generated with [Claude"',
    ]);
  });

  it("respects configured prefixes, labels, extra markers and commit_trailers: false", () => {
    const cfg = aiDetectionSchema.parse({
      enabled: true, branch_prefixes: ["bot/"], labels: ["robot"], markers: ["written by our LLM"], commit_trailers: false,
    });
    expect(detectAiGenerated(cfg, { branch: "cursor/x", commitMessages: ["Co-authored-by: Claude <c@anthropic.com>"] }).generated).toBe(false);
    expect(detectAiGenerated(cfg, { branch: "bot/x" }).signals).toEqual(['branch "bot/x" starts with "bot/"']);
    expect(detectAiGenerated(cfg, { labels: ["Robot"] }).generated).toBe(true);
    expect(detectAiGenerated(cfg, { title: "Change WRITTEN BY OUR LLM" }).signals).toEqual(['PR title mentions "written by our llm"']);
  });
});

describe("ai_detection in gate.yml", () => {
  const base = "version: 1\nchecks:\n  - {name: lint, type: script, run: 'true'}\n";
  it("defaults to disabled with sane defaults", () => {
    const cfg = parseGateConfig(base);
    expect(cfg.ai_detection).toMatchObject({ enabled: false, commit_trailers: true, policy: { require_checks: [], require_approval: false } });
    expect(cfg.ai_detection.branch_prefixes).toContain("cursor/");
  });

  it("accepts a policy that names existing checks and rejects unknown ones and unknown keys", () => {
    const ok = parseGateConfig(`${base}ai_detection:\n  enabled: true\n  policy: {require_checks: [lint], require_approval: true}\n`);
    expect(ok.ai_detection.policy).toEqual({ require_checks: ["lint"], require_approval: true });
    expect(() => parseGateConfig(`${base}ai_detection:\n  enabled: true\n  policy: {require_checks: [nope]}\n`)).toThrow(
      /ai_detection\.policy\.require_checks\.0: unknown check "nope"/,
    );
    expect(() => parseGateConfig(`${base}ai_detection: {enabled: true, typo: 1}\n`)).toThrow(GateConfigError);
  });
});

describe("evaluateGate with AI detection", () => {
  const passed = { name: "a", kind: "script" as const, required: true, status: "passed" as const, reason: "ok", exitCode: 0, durationMs: 1, output: "" };
  it("shows the AI verdict in the summary and carries it on the result", () => {
    const yes = evaluateGate([passed], { ai: { generated: true, signals: ['branch "cursor/x" starts with "cursor/"', "a|b"] } });
    expect(yes.summary).toContain('**AI-generated**: yes (branch "cursor/x" starts with "cursor/"; a\\|b)');
    expect(yes.ai?.generated).toBe(true);
    expect(evaluateGate([passed], { ai: { generated: false, signals: [] } }).summary).toContain("**AI-generated**: no signals found");
    const none = evaluateGate([passed]);
    expect(none.summary).not.toContain("AI-generated");
    expect(none.ai).toBeUndefined();
  });
});
